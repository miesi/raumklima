#!/usr/bin/env python3
"""Generate 1 bpp LVGL 9 fonts from DejaVu Sans.

Glyphs are rasterised by FreeType in monochrome mode (Pillow fontmode "1", hinted, no
anti-aliasing), so they are pixel-exact on the e-paper instead of thresholded grey.

Needs Pillow:  python3 -m pip install pillow
Run from the repo root:  python3 tools/mkfont.py
Output: components/ui/fonts/font_<name>.c (committed; regenerate only to change sizes or glyphs).

DejaVu fonts: Bitstream Vera license (+ public domain changes), see
components/ui/fonts/LICENSE-DejaVu. Embedding rendered bitmaps is permitted.
"""
import hashlib
import io
import os
import sys
import urllib.request
import zipfile

from PIL import Image, ImageDraw, ImageFont

ZIP_URL = "https://github.com/dejavu-fonts/dejavu-fonts/releases/download/version_2_37/dejavu-fonts-ttf-2.37.zip"
ZIP_SHA256 = "7576310b219e04159d35ff61dd4a4ec4cdba4f35c00e002a136f00e96a908b0a"

# ASCII printable plus what a climate display needs (degree, umlauts, micro, superscripts)
EXTRA = [0xB0, 0xB1, 0xB2, 0xB3, 0xB5, 0xB7, 0xC4, 0xD6, 0xDC, 0xDF, 0xE4, 0xF6, 0xFC]
DIGITS_ONLY = [ord(c) for c in " 0123456789:-.+"]

# name, ttf, pixel size, glyph set
FONTS = [
    ("dejavu_14", "DejaVuSans.ttf", 14, None),
    ("dejavu_18", "DejaVuSans.ttf", 18, None),
    ("dejavu_bold_24", "DejaVuSans-Bold.ttf", 24, None),
    ("dejavu_bold_32", "DejaVuSans-Bold.ttf", 32, None),
    ("dejavu_bold_72", "DejaVuSans-Bold.ttf", 72, DIGITS_ONLY),   # big clock
]

OUT_DIR = os.path.join("components", "ui", "fonts")


def fetch_fonts():
    data = urllib.request.urlopen(ZIP_URL).read()
    if hashlib.sha256(data).hexdigest() != ZIP_SHA256:
        sys.exit("DejaVu zip: SHA256 mismatch")
    z = zipfile.ZipFile(io.BytesIO(data))
    files = {}
    for n in z.namelist():
        base = os.path.basename(n)
        if base in ("DejaVuSans.ttf", "DejaVuSans-Bold.ttf", "LICENSE"):
            files[base] = z.read(n)
    return files


def render_glyph(font, cp):
    ch = chr(cp)
    adv = font.getlength(ch)
    left, top, right, bottom = font.getbbox(ch, anchor="ls")   # relative to baseline origin
    w, h = right - left, bottom - top
    if w <= 0 or h <= 0:
        return adv, 0, 0, 0, 0, []
    img = Image.new("1", (w + 4, h + 4), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"   # monochrome FreeType rendering
    d.text((2 - left, 2 - top), ch, font=font, fill=1, anchor="ls")
    bb = img.getbbox()
    if not bb:
        return adv, 0, 0, 0, 0, []
    x0, y0, x1, y1 = bb
    px = img.load()
    bits = [1 if px[x, y] else 0 for y in range(y0, y1) for x in range(x0, x1)]
    box_w, box_h = x1 - x0, y1 - y0
    ofs_x = left + x0 - 2
    bottom_px = top + y1 - 2           # y of the last row below the baseline (down = positive)
    ofs_y = -bottom_px                  # LVGL: baseline to box bottom, up = positive
    return adv, box_w, box_h, ofs_x, ofs_y, bits


def pack(bits):
    out = []
    for i in range(0, len(bits), 8):
        chunk = bits[i:i + 8] + [0] * (8 - len(bits[i:i + 8]))
        v = 0
        for b in chunk:
            v = (v << 1) | b
        out.append(v)
    return out


def ranges(cps):
    cps = sorted(cps)
    groups, start, prev = [], cps[0], cps[0]
    for c in cps[1:]:
        if c != prev + 1:
            groups.append((start, prev))
            start = c
        prev = c
    groups.append((start, prev))
    return groups


def gen(name, ttf_bytes, size, glyphs):
    font = ImageFont.truetype(io.BytesIO(ttf_bytes), size)
    ascent, descent = font.getmetrics()
    cps = glyphs or (list(range(0x20, 0x7F)) + EXTRA)
    cps = sorted(set(cps))

    bitmap, dscs = [], []
    for cp in cps:
        adv, bw, bh, ox, oy, bits = render_glyph(font, cp)
        packed = pack(bits)
        dscs.append((cp, len(bitmap), round(adv * 16), bw, bh, ox, oy))
        bitmap.extend(packed)

    sym = "font_" + name
    lines = []
    lines.append("// Generated by tools/mkfont.py - do not edit.")
    lines.append("// DejaVu Sans %spx, 1 bpp, monochrome FreeType rendering. License: LICENSE-DejaVu." % size)
    lines.append('#include "lvgl.h"')
    lines.append("")
    lines.append("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {")
    for i in range(0, len(bitmap), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 16]) + ",")
    if not bitmap:
        lines.append("    0x00,")
    lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {")
    lines.append("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
    for cp, bi, aw, bw, bh, ox, oy in dscs:
        lines.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, // U+%04X"
                     % (bi, aw, bw, bh, ox, oy, cp))
    lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_cmap_t cmaps[] = {")
    gid = 1
    groups = ranges(cps)
    for a, b in groups:
        lines.append("    {.range_start = %d, .range_length = %d, .glyph_id_start = %d, .unicode_list = NULL,"
                     " .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},"
                     % (a, b - a + 1, gid))
        gid += b - a + 1
    lines.append("};")
    lines.append("")
    lines.append("static const lv_font_fmt_txt_dsc_t font_dsc = {")
    lines.append("    .glyph_bitmap = glyph_bitmap,")
    lines.append("    .glyph_dsc = glyph_dsc,")
    lines.append("    .cmaps = cmaps,")
    lines.append("    .kern_dsc = NULL,")
    lines.append("    .kern_scale = 0,")
    lines.append("    .cmap_num = %d," % len(groups))
    lines.append("    .bpp = 1,")
    lines.append("    .kern_classes = 0,")
    lines.append("    .bitmap_format = 0,")
    lines.append("};")
    lines.append("")
    lines.append("const lv_font_t %s = {" % sym)
    lines.append("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
    lines.append("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
    lines.append("    .line_height = %d," % (ascent + descent))
    lines.append("    .base_line = %d," % descent)
    lines.append("    .subpx = LV_FONT_SUBPX_NONE,")
    lines.append("    .underline_position = -2,")
    lines.append("    .underline_thickness = 1,")
    lines.append("    .static_bitmap = 1,")
    lines.append("    .dsc = &font_dsc,")
    lines.append("    .fallback = NULL,")
    lines.append("    .user_data = NULL,")
    lines.append("};")
    with open(os.path.join(OUT_DIR, sym + ".c"), "w") as f:
        f.write("\n".join(lines) + "\n")
    return sym


def main():
    files = fetch_fonts()
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "LICENSE-DejaVu"), "wb") as f:
        f.write(files["LICENSE"])
    syms = [gen(n, files[ttf], size, g) for n, ttf, size, g in FONTS]
    with open(os.path.join(OUT_DIR, "fonts.h"), "w") as f:
        f.write("// Generated by tools/mkfont.py - do not edit.\n#pragma once\n#include \"lvgl.h\"\n\n")
        for s in syms:
            f.write("LV_FONT_DECLARE(%s);\n" % s)
    print("wrote", ", ".join(syms))


if __name__ == "__main__":
    main()
